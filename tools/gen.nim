## Regenerates `src/libcapstone/gen_v<major>.nim` from the Capstone headers
## that pkg-config points at. Maintainer tool: run it with `nimble regen`, or
## `nim c tools/gen.nim` (the switches it needs are in `gen.nims`).
##
## Requirements: the Futhark version pinned in `libcapstone.nimble`, its `opir`
## helper on the PATH, a `clang` on the PATH with the same major version as the
## libclang `opir` was linked against, and Nim >= 2.4.
##
## To generate for another Capstone than the system one:
## `PKG_CONFIG_PATH=<prefix>/lib/pkgconfig nimble regen`.

import std/[json, os, strutils]
import futhark

proc pkgConfig(query: string): string {.compileTime.} =
  let (output, exitCode) = gorgeEx("pkg-config " & query & " capstone")
  doAssert exitCode == 0, "pkg-config " & query & " capstone failed: " & output
  output.strip

const
  version = pkgConfig("--modversion")
  major = parseInt(version.split('.')[0])
  # The -I flag, not the `includedir` variable: that one is `<prefix>/include/capstone`
  # in Capstone 4 and `<prefix>/include` in Capstone 5.
  includeDir = pkgConfig("--cflags-only-I").splitWhitespace[0][2 .. ^1]
  output = currentSourcePath().parentDir.parentDir / "src" / "libcapstone" /
           ("gen_v" & $major & ".nim")

static:
  doAssert major == 4, "no bindings are kept for Capstone " & version

const prelude = """
## Capstone """ & version & """ C API, generated by `tools/gen.nim` with Futhark. Do not edit:
## fix the generator or `raw.nim` instead, then run `nimble regen`.

type
  cs_mode* = distinct uint32
    ## Bit set of `CS_MODE_*` values; combine them with `or`. An enum in C, but a
    ## Nim enum cannot hold a combination of its members.
"""

type cs_mode = distinct uint32 # for this compilation; the output gets it from `prelude`

proc rename(name: string; kind: SymbolKind; partof: string; overloading: var bool): string =
  ## Names for what C leaves unnamed or Nim cannot spell: `type` is a keyword
  ## (Futhark would emit `type_field`) and anonymous unions have no name at all
  ## (Futhark would emit `anon0`).
  result = name
  if kind == Field:
    if name == "type":
      result = "kind"
    elif name == "anon0":
      result =
        if partof == "struct_cs_detail": "arch"        # x86 / arm / arm64 / ...
        elif partof == "struct_cs_x86": "flags"        # eflags / fpu_flags
        elif partof == "struct_m68k_op_size": "size"   # cpu_size / fpu_size
        else: "value"                                  # operand payload: reg / imm / mem / ...

proc reshape(opir: JsonNode): JsonNode =
  ## Adjusts what `opir` read from the headers before Futhark turns it into Nim.
  result = newJArray()
  for node in opir:
    let kind = node["kind"].str
    if kind == "enum" and node{"name"}.getStr == "enum_cs_mode":
      # `enum cs_mode` becomes constants of the distinct type in `prelude`.
      for field in node["fields"]:
        result.add %*{"kind": "const", "file": node["file"], "position": node["position"],
                      "name": field["name"],
                      "value": parseBiggestInt(field["value"].str) and 0xFFFF_FFFF,
                      "type": {"kind": "base", "value": "cs_mode"}}
    elif kind == "typedef" and node["name"].str == "cs_mode":
      discard
    else:
      result.add node

# Futhark 0.16.1 only accepts a closure here.
const reshapeCallback: proc (opir: JsonNode): JsonNode {.closure.} = reshape

importc:
  outputPath output
  path includeDir
  renameCallback rename
  addOpirCallback reshapeCallback
  "capstone.h"

static:
  # Futhark records where each declaration came from; keep that independent of
  # where the headers happened to be installed.
  writeFile(output, prelude &
    readFile(output).replace(includeDir & "/", "capstone/").strip(leading = false) & "\n")
  echo "wrote ", output, " from the Capstone ", version, " headers in ", includeDir
